// Русское чтение → украинское (э→е, и→і, ы→и, е→є, ё→ьо)
function ukReading(s) {
  return s
    .replace(/и/g, "і").replace(/И/g, "І")
    .replace(/ы/g, "и")
    .replace(/е/g, "є")
    .replace(/э/g, "е").replace(/Э/g, "Е")
    .replace(/([бвгджзклмнпрстфхцчшщ])ё/g, "$1ьо").replace(/ё/g, "йо")
    .replace(/и́/g, "і́");
}
